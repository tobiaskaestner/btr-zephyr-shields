# --- config-sheet.md: facts, not bytes -------------------------------------

# Synthetic, and deliberately exercising every section kind in one
# document. Two of those kinds have ZERO golden coverage and are proven
# only here: a Wires section (no rig in the corpus declares wires:, so no
# golden contains one -- re-check with a grep for "## Wires" over the
# goldens tree) and a Chip-selects bullet with no gpio_map entry, hence no
# SoC suffix. Both shapes are additionally generated FROM the emitter
# below, so this hand-written copy cannot drift away from what
# emitter/sheet.py actually produces without a test failing.
SHEET_GOLDEN = textwrap.dedent("""\
    # Physical configuration sheet — rig `test_rig`

    <!-- generated by rigc — do not edit; the rig file is the source of truth (R3) -->

    Board: **test_board/test_soc/rig**

    ## Socket assignment

    | instance | shield | socket |
    |---|---|---|
    | flash_a | flash_click | sock1 |
    | temp_a | temp_click | sock2 |

    ## Straps / jumpers

    - **temp_a** (sock2): set **ADDR jumper** to state 0 → device address 0x48
    - **wifi_a** (sock3): set **IRQ select** to state 1 → routed to pin D2

    ## Chip-selects

    - flash_a/nor: CS index 0, CS → SoC gpioa pin 3
    - flash_a/nor2: CS index 1, D9

    ## PWM / analog pin-mux (board-provided pinctrl)

    The expander enables these controllers; the SoC pin-mux for each pin is board-provided and must be applied (stubbed):

    - light_1/light (sock4 SIG0) → ADC adc ch0: mux the pin to the controller

    ## Wires

    - connect **a.node1** → **b.node2** — via header position 7
    - connect **c.node3** → **d.node4** — ad-hoc jumper wire (in no connector)

    ## Parameters

    | instance | device | property | value |
    |---|---|---|---|
    | flash_a | dev | zephyr,code | INPUT_KEY_0 (11) |
    | temp_a | dev | zephyr,code | 5 |
    """)


def test_parses_every_section_kind() -> None:
    facts = parse_config_sheet(SHEET_GOLDEN)
    assert facts.rig_name == "test_rig"
    assert facts.board == "test_board/test_soc/rig"
    assert set(facts.sections) == {
        "socket_assignment", "straps_jumpers", "chip_selects", "pwm",
        "wires", "parameters"}


def test_socket_assignment_rows() -> None:
    facts = parse_config_sheet(SHEET_GOLDEN)
    assert facts.sections["socket_assignment"] == (
        ("flash_a", "flash_click", "sock1"),
        ("temp_a", "temp_click", "sock2"))


def test_straps_and_jumpers_are_both_recognised_in_one_section() -> None:
    facts = parse_config_sheet(SHEET_GOLDEN)
    assert facts.sections["straps_jumpers"] == (
        ("strap", "temp_a", "sock2", "ADDR jumper", "0", "0x48"),
        ("jumper", "wifi_a", "sock3", "IRQ select", "1", "D2"))


def test_chip_select_with_and_without_gpio_map_entry() -> None:
    facts = parse_config_sheet(SHEET_GOLDEN)
    assert facts.sections["chip_selects"] == (
        ("flash_a", "nor", "0", "CS", "gpioa", "3"),
        ("flash_a", "nor2", "1", "D9", "", ""))


def test_wires_section_has_no_golden_coverage_so_is_proven_here() -> None:
    """No rig in the corpus declares wires:, so no golden carries a Wires
    section and this is the extractor's only proof it recognises either
    shape -- a routed header position and an ad-hoc jumper wire. Re-check
    the premise with a grep for "## Wires" over the goldens tree."""
    facts = parse_config_sheet(SHEET_GOLDEN)
    assert facts.sections["wires"] == (
        ("a.node1", "b.node2", "via header position 7"),
        ("c.node3", "d.node4", "ad-hoc jumper wire (in no connector)"))


def test_identical_sheet_text_compares_equal() -> None:
    assert compare_config_sheet(SHEET_GOLDEN, SHEET_GOLDEN) is None


