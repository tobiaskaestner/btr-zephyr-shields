# --- the zero-coverage shapes, GENERATED from the emitter -----------------
# The two shapes no golden exercises were previously pinned by the
# hand-written fixture above, and a hand-written fixture can describe
# output the emitter cannot produce (a route was written as a position
# NAME where analyzer/wires.py resolves routes to an integer INDEX). These
# drive the real renderer instead, so fixture drift becomes impossible
# rather than something a reader has to notice.


def _generated_sheet() -> str:
    """config-sheet.md as the REAL emitter renders it, over a synthetic
    Solved carrying both zero-golden-coverage shapes: a wire routed
    through a header position and an ad-hoc one, and a chip-select with a
    gpio_map entry alongside one without."""
    from rigc.analyzer import Solved
    from rigc.diag import SourceRef
    from rigc.emitter.sheet import render_sheet
    from rigc.model import (BoardSocket, ConnectorType, Instance, Rig, Shield,
                            Wire, WireEnd)

    src = SourceRef("f.yml", 1, "k")
    ctype = ConnectorType(
        name="t", positions={}, index2name={0: "CS", 9: "D9"},
        bus_proxies=[], stackable=False, cs_pool=[])
    mapped = BoardSocket(
        label="sock1", path="/s1", type_name="t",
        gpio_map={0: ("gpioa", 3, 0)}, buses={}, cs_pool=None)
    unmapped = BoardSocket(
        label="sock2", path="/s2", type_name="t", gpio_map={}, buses={},
        cs_pool=None)
    shield = Shield(name="flash_click", label="fc", plugs="t")
    insts = [Instance(name="flash_a", shield=shield, socket="sock1"),
            Instance(name="flash_b", shield=shield, socket="sock2")]
    frm = WireEnd(instance_name="a", node="node1", src=src)
    to = WireEnd(instance_name="b", node="node2", src=src)
    solved = Solved(
        sockets={"flash_a": mapped, "flash_b": unmapped},
        cs={("flash_a", "nor"): (0, 0), ("flash_b", "nor"): (1, 9)},
        wires=[Wire(frm=frm, to=to, route=7, src=src),
               Wire(frm=frm, to=to, route="adhoc", src=src)])
    rig = Rig(name="test_rig", board="test_board/test_soc/rig",
             instances=insts)
    return render_sheet(rig, solved, {"t": ctype}, workdir="/does-not-matter")


